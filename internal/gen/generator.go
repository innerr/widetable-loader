// Package gen implements the "gen" subcommand: synthetic wide-table data
// generation, one CSV file per key segment.
//
// Row model (generic, parameter-driven):
//
//	id (BIGINT primary key) | f1..fF (fixed columns, always filled) |
//	c000001..cN (declared columns, sparsely filled)
//
// The first --index-fields declared columns are filled on every row
// (they carry secondary indexes); the remaining filled columns are chosen
// uniformly at random. Declared column types rotate through
// int / string / double / bool / json.
package gen

import (
	"fmt"
	"math/rand"
	"strconv"

	"github.com/innerr/widetable-loader/internal/genkey"
)

// Config carries every parameter that determines the generated bytes.
// The same Config + seed reproduces byte-identical output.
type Config struct {
	TotalRows   uint64
	Segments    uint64
	Scatter     string // blocked | none | mul-hash
	GapFactor   uint64
	Seed        uint64
	Fields      int
	FileCols    int
	FixedCols   int
	IndexFields int
	Fill        int
	RowWidth    int
	FillBuckets int // >0: cycle through this many pre-picked column sets instead of per-row random
}

// RowsPerSeg is the fixed row count of every segment.
func (c Config) RowsPerSeg() uint64 { return c.TotalRows / c.Segments }

// Stride is the key-space stride of one segment (with gaps for blocked).
func (c Config) Stride() uint64 {
	if c.Scatter == "blocked" {
		return c.RowsPerSeg() * c.GapFactor
	}
	return c.RowsPerSeg()
}

func (c Config) layout(segment uint64) (genkey.Layout, error) {
	switch c.Scatter {
	case "blocked", "none":
		return genkey.Identity{Base: segment * c.Stride()}, nil
	case "mul-hash":
		return genkey.NewMulHash(c.Seed), nil
	}
	return nil, fmt.Errorf("unknown scatter %q (blocked | none | mul-hash)", c.Scatter)
}

// Generator reproduces rows of one segment. Next must be called in
// increasing seq order starting from the segment's first global sequence:
// the rng state advances with every row, so skipping ahead means calling
// Next and discarding the result.
type Generator struct {
	cfg     Config
	layout  genkey.Layout
	rng     *rand.Rand
	strLen  int
	perm    []int
	record  []string
	buckets [][]int // FillBuckets pre-picked column sets (nil when off)
	rowIdx  uint64   // row counter for bucket cycling
	row0    uint64 // first global sequence of the segment
	row1    uint64 // one past the last
	pending uint64 // next seq to emit
}

func NewGenerator(cfg Config, segment uint64) (*Generator, error) {
	if segment >= cfg.Segments {
		return nil, fmt.Errorf("segment must be < segments")
	}
	if cfg.Fill > cfg.Fields || cfg.IndexFields > cfg.Fill {
		return nil, fmt.Errorf("require index-fields <= fill <= fields")
	}
	if cfg.FileCols == 0 {
		cfg.FileCols = cfg.Fields
	}
	if cfg.FileCols > cfg.Fields || cfg.Fill > cfg.FileCols {
		return nil, fmt.Errorf("require fill <= file-cols <= fields")
	}
	layout, err := cfg.layout(segment)
	if err != nil {
		return nil, err
	}
	g := &Generator{
		cfg:    cfg,
		layout: layout,
		rng:    rand.New(rand.NewSource(int64(cfg.Seed*1000003 + segment))),
		perm:   make([]int, cfg.FileCols-cfg.IndexFields),
		record: make([]string, 1+cfg.FixedCols+cfg.FileCols),
		row0:   segment * cfg.RowsPerSeg(),
	}
	g.row1 = g.row0 + cfg.RowsPerSeg()
	g.pending = g.row0
	// Long values are carried by string/json columns only (2 of 5 rotated
	// types), so spread the target width over them, not over all filled
	// columns.
	g.strLen = (cfg.RowWidth * 5) / (cfg.Fill * 2)
	if g.strLen < 8 {
		g.strLen = 8
	}
	for i := range g.perm {
		g.perm[i] = cfg.IndexFields + i
	}
	return g, nil
}

// Next renders the row with global sequence seq, advancing the rng.
// seq must equal the pending sequence (rows are strictly sequential).
// The returned slice is reused by the next call.
func (g *Generator) Next(seq uint64) ([]string, error) {
	if seq != g.pending {
		return nil, fmt.Errorf("Next called out of order: want %d, got %d", g.pending, seq)
	}
	if seq >= g.row1 {
		return nil, fmt.Errorf("seq %d past segment end %d", seq, g.row1)
	}
	g.pending++
	cfg := g.cfg
	for i := range g.record {
		g.record[i] = ""
	}
	g.record[0] = strconv.FormatUint(g.layout.ID(seq), 10)
	for c := 1; c <= cfg.FixedCols; c++ {
		g.record[c] = fixedValue(c, seq)
	}
	// Index columns are always filled.
	for c := 0; c < cfg.IndexFields; c++ {
		g.record[1+cfg.FixedCols+c] = value(c, seq, g.strLen, g.rng)
	}
	// The rest: partial Fisher-Yates to pick fill-indexFields columns.
	need := cfg.Fill - cfg.IndexFields
	if cfg.FillBuckets > 0 {
		if len(g.buckets) == 0 {
			// Pre-pick FillBuckets column sets once (deterministic from rng).
			g.buckets = make([][]int, cfg.FillBuckets)
			for b := range g.buckets {
				perm := make([]int, len(g.perm))
				copy(perm, g.perm)
				set := make([]int, need)
				for i := 0; i < need; i++ {
					j := i + g.rng.Intn(len(perm)-i)
					perm[i], perm[j] = perm[j], perm[i]
					set[i] = perm[i]
				}
				g.buckets[b] = set
			}
		}
		set := g.buckets[int(g.rowIdx)%cfg.FillBuckets]
		for _, c := range set {
			g.record[1+cfg.FixedCols+c] = value(c, seq, g.strLen, g.rng)
		}
		g.rowIdx++
		return g.record, nil
	}
	for i := 0; i < need; i++ {
		j := i + g.rng.Intn(len(g.perm)-i)
		g.perm[i], g.perm[j] = g.perm[j], g.perm[i]
		g.record[1+cfg.FixedCols+g.perm[i]] = value(g.perm[i], seq, g.strLen, g.rng)
	}
	return g.record, nil
}

// ColumnNames returns the file/header column order (id, fixed, declared set in the file).
func (cfg Config) ColumnNames() []string {
	names := make([]string, 0, 1+cfg.FixedCols+cfg.FileCols)
	names = append(names, "id")
	for c := 1; c <= cfg.FixedCols; c++ {
		names = append(names, fmt.Sprintf("f%d", c))
	}
	for c := 1; c <= cfg.FileCols; c++ {
		names = append(names, fmt.Sprintf("c%06d", c))
	}
	return names
}

const letters = "abcdefghijklmnopqrstuvwxyz0123456789"

// fixedValue fills fixed columns by position: f1 increments like a
// timestamp, f2 is a constant zero flag, the rest cycle cheaply.
func fixedValue(col int, seq uint64) string {
	switch col {
	case 1:
		return strconv.FormatUint(1700000000+seq, 10)
	case 2:
		return "0"
	default:
		return fmt.Sprintf("f%d-%d", col, seq%997)
	}
}

// value renders a column value by its rotated type. String and json columns
// carry the row-width payload; numeric columns stay short.
func value(col int, seq uint64, strLen int, rng *rand.Rand) string {
	switch col % 5 {
	case 0:
		return strconv.FormatUint(seq%1000000, 10)
	case 2:
		return strconv.FormatFloat(float64(seq%1000000)/97.0, 'f', 2, 64)
	case 3:
		if seq%2 == 0 {
			return "true"
		}
		return "false"
	case 4:
		return `{"k":"` + randString(strLen, rng) + `"}`
	default:
		return randString(strLen, rng)
	}
}

func randString(n int, rng *rand.Rand) string {
	b := make([]byte, n)
	for i := range b {
		b[i] = letters[rng.Intn(len(letters))]
	}
	return string(b)
}
