// Package gen implements the "gen" subcommand: synthetic wide-table data
// generation, one CSV file per key segment.
//
// Row model (generic, parameter-driven):
//
//	id (BIGINT primary key) | f1..fF (fixed columns, always filled) |
//	c000001..cN (declared columns, sparsely filled)
//
// The first --index-fields declared columns are filled on every row
// (they carry secondary indexes); the remaining filled columns are chosen
// uniformly at random. Declared column types rotate through
// int / string / double / bool / json.
package gen

import (
	"bufio"
	"context"
	"fmt"
	"math/rand"
	"strconv"
	"strings"

	"github.com/innerr/widetable-loader/internal/genkey"
	"github.com/innerr/widetable-loader/internal/sqlutil"
)

// Config carries every parameter that determines the generated bytes.
// The same Config + seed reproduces byte-identical output.
type Config struct {
	TotalRows   uint64
	Segments    uint64
	Scatter     string // blocked | none | mul-hash
	GapFactor   uint64
	Seed        uint64
	Fields      int
	FileCols    int
	FixedCols   int
	IndexFields int
	IndexCols   []int // explicit declared-column indexes (0-based); overrides IndexFields
	Fill        int
	RowWidth    int
	FillBuckets int // >0: cycle through this many pre-picked column sets instead of per-row random
}

// RowsPerSeg is the fixed row count of every segment.
func (c Config) RowsPerSeg() uint64 { return c.TotalRows / c.Segments }

// Stride is the key-space stride of one segment (with gaps for blocked).
func (c Config) Stride() uint64 {
	if c.Scatter == "blocked" {
		return c.RowsPerSeg() * c.GapFactor
	}
	return c.RowsPerSeg()
}

func (c Config) layout(segment uint64) (genkey.Layout, error) {
	switch c.Scatter {
	case "blocked", "none":
		return genkey.Identity{Base: segment * (c.Stride() - c.RowsPerSeg())}, nil
	case "mul-hash":
		return genkey.NewMulHash(c.Seed), nil
	case "hash32":
		return genkey.Hash32Prefix{}, nil
	}
	return nil, fmt.Errorf("unknown scatter %q (blocked | none | mul-hash | hash32)", c.Scatter)
}

// Layout exposes the key layout of one segment (bench uses it to derive
// occupied/gap key ranges from the same parameters as gen).
func (c Config) Layout(segment uint64) (genkey.Layout, error) {
	return c.layout(segment)
}

// Generator reproduces rows of one segment. Next must be called in
// increasing seq order starting from the segment's first global sequence:
// the rng state advances with every row, so skipping ahead means calling
// Next and discarding the result.
type Generator struct {
	cfg       Config
	layout    genkey.Layout
	rng       *rand.Rand
	strLen    int
	indexCols []int // file columns carrying secondary indexes (int/double rotations)
	perm      []int
	record    []string
	buckets   [][]int // FillBuckets pre-picked column sets (nil when off)
	rowIdx    uint64  // row counter for bucket cycling
	row0      uint64  // first global sequence of the segment
	row1      uint64  // one past the last
	pending   uint64  // next seq to emit
}

func NewGenerator(cfg Config, segment uint64) (*Generator, error) {
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	if segment >= cfg.Segments {
		return nil, fmt.Errorf("segment must be < segments")
	}
	if cfg.Fill > cfg.Fields || cfg.IndexFields > cfg.Fill {
		return nil, fmt.Errorf("require index-fields <= fill <= fields")
	}
	if cfg.FileCols == 0 {
		cfg.FileCols = cfg.Fields
	}
	if cfg.FileCols > cfg.Fields || cfg.Fill > cfg.FileCols {
		return nil, fmt.Errorf("require fill <= file-cols <= fields")
	}
	layout, err := cfg.layout(segment)
	if err != nil {
		return nil, err
	}
	// An explicit index-cols list names the columns that carry secondary
	// indexes. Without it, index columns must carry an indexable rotated type
	// (int at col%5==0, double at col%5==2): wide-table secondary indexes only
	// accept INT/DOUBLE/short VARCHAR, so text (1), bool (3) and json (4)
	// rotations are skipped when picking the first IndexFields columns.
	indexCols := append([]int(nil), cfg.IndexCols...)
	if len(indexCols) == 0 {
		for c := 0; c < cfg.FileCols && len(indexCols) < cfg.IndexFields; c++ {
			if c%5 == 0 || c%5 == 2 {
				indexCols = append(indexCols, c)
			}
		}
		if len(indexCols) < cfg.IndexFields {
			return nil, fmt.Errorf("not enough indexable columns (int/double rotations) for index-fields=%d", cfg.IndexFields)
		}
	}
	isIndex := make(map[int]bool, len(indexCols))
	for _, c := range indexCols {
		isIndex[c] = true
	}
	g := &Generator{
		cfg:       cfg,
		layout:    layout,
		rng:       rand.New(rand.NewSource(int64(cfg.Seed*1000003 + segment))),
		indexCols: indexCols,
		perm:      make([]int, cfg.FileCols-len(indexCols)),
		record:    make([]string, 1+cfg.FixedCols+cfg.FileCols),
		row0:      segment * cfg.RowsPerSeg(),
	}
	g.row1 = g.row0 + cfg.RowsPerSeg()
	g.pending = g.row0
	// Long values are carried by string/json columns only (2 of 5 rotated
	// types), so spread the target width over them, not over all filled
	// columns.
	if cfg.Fill > 0 {
		g.strLen = (cfg.RowWidth * 5) / (cfg.Fill * 2)
	}
	if g.strLen < 8 {
		g.strLen = 8
	}
	for i, c := 0, 0; i < len(g.perm); c++ {
		if isIndex[c] {
			continue
		}
		g.perm[i] = c
		i++
	}
	return g, nil
}

// Validate checks the sequence domain and dimensions before allocation.
func (this Config) Validate() error {
	if this.Segments == 0 || this.TotalRows == 0 || this.TotalRows%this.Segments != 0 {
		return fmt.Errorf("total-rows must be positive and divisible by positive segments")
	}
	if this.Fields < 0 || this.FixedCols < 0 || this.Fill < 0 || this.IndexFields < 0 ||
		this.FileCols < 0 || this.FillBuckets < 0 || this.RowWidth < 0 {
		return fmt.Errorf("column counts and widths must be nonnegative")
	}
	fileCols := this.FileCols
	if fileCols == 0 {
		fileCols = this.Fields
	}
	if this.IndexFields > this.Fill || this.Fill > fileCols || fileCols > this.Fields {
		return fmt.Errorf("require index-fields <= fill <= file-cols <= fields")
	}
	seen := make(map[int]bool, len(this.IndexCols))
	for _, c := range this.IndexCols {
		if c < 0 || c >= fileCols {
			return fmt.Errorf("index-cols entry %d outside 0..%d", c, fileCols-1)
		}
		if seen[c] {
			return fmt.Errorf("index-cols contains duplicate column %d", c)
		}
		seen[c] = true
	}
	if len(this.IndexCols) > this.Fill {
		return fmt.Errorf("require len(index-cols) <= fill")
	}
	const maxID = uint64(1<<63 - 1)
	if this.TotalRows > maxID {
		return fmt.Errorf("total-rows exceeds signed BIGINT range")
	}
	switch this.Scatter {
	case "hash32":
		if this.TotalRows > 1<<32 {
			return fmt.Errorf("hash32 supports at most 2^32 rows")
		}
	case "blocked":
		if this.GapFactor == 0 || this.TotalRows > maxID/this.GapFactor {
			return fmt.Errorf("blocked layout requires a positive gap-factor within signed BIGINT range")
		}
	case "none", "mul-hash":
	default:
		return fmt.Errorf("unknown scatter %q", this.Scatter)
	}
	return nil
}

// Next renders the row with global sequence seq, advancing the rng.
// seq must equal the pending sequence (rows are strictly sequential).
// The returned slice is reused by the next call.
func (g *Generator) Next(seq uint64) ([]string, error) {
	if seq != g.pending {
		return nil, fmt.Errorf("Next called out of order: want %d, got %d", g.pending, seq)
	}
	if seq >= g.row1 {
		return nil, fmt.Errorf("seq %d past segment end %d", seq, g.row1)
	}
	g.pending++
	cfg := g.cfg
	for i := range g.record {
		g.record[i] = ""
	}
	g.record[0] = strconv.FormatUint(g.layout.ID(seq), 10)
	for c := 1; c <= cfg.FixedCols; c++ {
		g.record[c] = fixedValue(c, seq)
	}
	// Index columns are always filled.
	for _, c := range g.indexCols {
		g.record[1+cfg.FixedCols+c] = value(c, seq, g.strLen, g.rng)
	}
	// The rest: partial Fisher-Yates to pick fill-len(indexCols) columns.
	need := cfg.Fill - len(g.indexCols)
	if cfg.FillBuckets > 0 {
		if len(g.buckets) == 0 {
			// Pre-pick FillBuckets column sets once (deterministic from rng).
			g.buckets = make([][]int, cfg.FillBuckets)
			for b := range g.buckets {
				perm := make([]int, len(g.perm))
				copy(perm, g.perm)
				set := make([]int, need)
				for i := 0; i < need; i++ {
					j := i + g.rng.Intn(len(perm)-i)
					perm[i], perm[j] = perm[j], perm[i]
					set[i] = perm[i]
				}
				g.buckets[b] = set
			}
		}
		set := g.buckets[int(g.rowIdx)%cfg.FillBuckets]
		for _, c := range set {
			g.record[1+cfg.FixedCols+c] = value(c, seq, g.strLen, g.rng)
		}
		g.rowIdx++
		return g.record, nil
	}
	for i := 0; i < need; i++ {
		j := i + g.rng.Intn(len(g.perm)-i)
		g.perm[i], g.perm[j] = g.perm[j], g.perm[i]
		g.record[1+cfg.FixedCols+g.perm[i]] = value(g.perm[i], seq, g.strLen, g.rng)
	}
	return g.record, nil
}

// ColumnNames returns the file/header column order (id, fixed, declared set in the file).
func (cfg Config) ColumnNames() []string {
	fileCols := cfg.FileCols
	if fileCols == 0 {
		fileCols = cfg.Fields
	}
	names := make([]string, 0, 1+cfg.FixedCols+fileCols)
	names = append(names, "id")
	for c := 1; c <= cfg.FixedCols; c++ {
		names = append(names, fmt.Sprintf("f%d", c))
	}
	for c := 1; c <= fileCols; c++ {
		names = append(names, fmt.Sprintf("c%06d", c))
	}
	return names
}

const letters = "abcdefghijklmnopqrstuvwxyz0123456789"

// fixedValue fills fixed columns by position: f1 increments like a
// timestamp, f2 is a constant zero flag, the rest cycle cheaply.
func fixedValue(col int, seq uint64) string {
	switch col {
	case 1:
		return strconv.FormatUint(1700000000+seq, 10)
	case 2:
		return "0"
	default:
		return fmt.Sprintf("f%d-%d", col, seq%997)
	}
}

// value renders a column value by its rotated type. String and json columns
// carry the row-width payload; numeric columns stay short.
func value(col int, seq uint64, strLen int, rng *rand.Rand) string {
	switch col % 5 {
	case 0:
		return strconv.FormatUint(seq%1000000, 10)
	case 2:
		return strconv.FormatFloat(float64(seq%1000000)/97.0, 'f', 2, 64)
	case 3:
		if seq%2 == 0 {
			return "true"
		}
		return "false"
	case 4:
		return `{"k":"` + randString(strLen, rng) + `"}`
	default:
		return randString(strLen, rng)
	}
}

func randString(n int, rng *rand.Rand) string {
	b := make([]byte, n)
	for i := range b {
		b[i] = letters[rng.Intn(len(letters))]
	}
	return string(b)
}

// WriteSQL writes every row of the generator's segment as INSERT
// statements, one statement per line, up to multiRow rows per statement.
// Only rows sharing the same filled-column set can share a statement, so a
// group breaks whenever the pattern changes; with fill == file-cols every
// row matches and statements are exactly multiRow rows. Empty columns are
// omitted from the column list (the table default applies), matching the
// csv path's insertEncoder semantics. The same Config + seed reproduces
// byte-identical output, matching the CSV rendering row for row.
func (g *Generator) WriteSQL(w *bufio.Writer, table string, multiRow int, upsert bool) error {
	return g.WriteSQLContext(context.Background(), w, table, multiRow, upsert)
}

// WriteSQLContext is the cancellable variant of WriteSQL.
func (g *Generator) WriteSQLContext(ctx context.Context, w *bufio.Writer, table string, multiRow int, upsert bool) error {
	if multiRow < 1 {
		return fmt.Errorf("multi-row must be >= 1 for SQL output")
	}
	if table == "" {
		return fmt.Errorf("table name is required for SQL output")
	}
	var cols []string
	var group [][]string
	writeGroup := func() error {
		if len(group) == 0 {
			return nil
		}
		var b strings.Builder
		b.WriteString("INSERT INTO ")
		b.WriteString(sqlutil.QuoteIdentifier(table))
		b.WriteString(" (")
		b.WriteString(strings.Join(cols, ","))
		b.WriteString(") VALUES ")
		for r, rec := range group {
			if r > 0 {
				b.WriteByte(',')
			}
			b.WriteByte('(')
			first := true
			for _, v := range rec {
				if v == "" {
					continue
				}
				if !first {
					b.WriteByte(',')
				}
				b.WriteString(sqlLiteral(v))
				first = false
			}
			b.WriteByte(')')
		}
		if upsert {
			b.WriteString(" ON DUPLICATE KEY UPDATE ")
			for i, c := range cols {
				if i > 0 {
					b.WriteByte(',')
				}
				b.WriteString(c + "=VALUES(" + c + ")")
			}
		}
		b.WriteString(";\n")
		if _, err := w.WriteString(b.String()); err != nil {
			return err
		}
		group = group[:0]
		return nil
	}
	for seq := g.row0; seq < g.row1; seq++ {
		if err := ctx.Err(); err != nil {
			return err
		}
		rec, err := g.Next(seq)
		if err != nil {
			return err
		}
		if len(group) > 0 && (!sameFilled(group[0], rec) || len(group) == multiRow) {
			if err := writeGroup(); err != nil {
				return err
			}
		}
		if len(group) == 0 {
			cols = cols[:0]
			for i, v := range rec {
				if v != "" {
					cols = append(cols, sqlutil.QuoteIdentifier(g.columnName(i)))
				}
			}
		}
		dup := make([]string, len(rec))
		copy(dup, rec)
		group = append(group, dup)
	}
	if err := writeGroup(); err != nil {
		return err
	}
	return w.Flush()
}

// columnName returns the file/header name of record index i (id, fixed
// columns, then declared columns), matching ColumnNames.
func (g *Generator) columnName(i int) string {
	if i == 0 {
		return "id"
	}
	fixed := g.cfg.FixedCols
	if i <= fixed {
		return fmt.Sprintf("f%d", i)
	}
	return fmt.Sprintf("c%06d", i-fixed)
}

func sameFilled(a, b []string) bool {
	for i := range a {
		if (a[i] == "") != (b[i] == "") {
			return false
		}
	}
	return true
}

func sqlLiteral(v string) string {
	return "'" + strings.ReplaceAll(v, "'", "''") + "'"
}
